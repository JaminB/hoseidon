// Bundles apps/server/drizzle (journal + SQL) into src/migrations.gen.ts for
// drizzle-orm/durable-sqlite's migrator, which takes the files as data (a Worker has no fs).
// `--check` fails instead of writing when the committed file is stale (CI, build).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const drizzleDir = join(here, '../../server/drizzle');
const out = join(here, '../src/migrations.gen.ts');

const journal = JSON.parse(readFileSync(join(drizzleDir, 'meta/_journal.json'), 'utf8'));
const migrations = {};
for (const entry of journal.entries) {
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  // Normalize line endings so the file is the same on Windows and Linux checkouts.
  migrations[key] = readFileSync(join(drizzleDir, `${entry.tag}.sql`), 'utf8').replace(
    /\r\n/g,
    '\n',
  );
}

const body = `// Generated by scripts/gen-migrations.mjs from apps/server/drizzle. Do not edit.
// Regenerate with: pnpm --filter @hoseidon/worker gen
export default ${JSON.stringify({ journal, migrations }, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== body) {
    console.error('src/migrations.gen.ts is stale: run `pnpm --filter @hoseidon/worker gen`.');
    process.exit(1);
  }
} else {
  writeFileSync(out, body);
  console.log(`wrote ${out} (${journal.entries.length} migrations)`);
}
